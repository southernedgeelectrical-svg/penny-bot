// Bundles game/index.html into a JS module the app can load offline.
// Run after editing the game: node scripts/build-game.js
const fs = require('fs');
const path = require('path');
const src = path.join(__dirname, '..', 'game', 'index.html');
const out = path.join(__dirname, '..', 'game', 'gameHtml.js');
const html = fs.readFileSync(src, 'utf8');
fs.writeFileSync(out, '// Generated by scripts/build-game.js from game/index.html. Do not edit by hand.\nexport default ' + JSON.stringify(html) + ';\n');
console.log(`Wrote ${out} (${(html.length / 1024).toFixed(1)} KB)`);
