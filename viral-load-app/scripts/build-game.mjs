// Builds src/gameHtml.js from game/viral-load.html: wraps it in a full HTML document
// and inlines the Google Fonts (latin subset) so the game looks right offline.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
let html = readFileSync(path.join(root, 'game/viral-load.html'), 'utf8');
const UA = 'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Mobile Safari/537.36';

const linkRe = /<link rel="stylesheet" href="(https:\/\/fonts\.googleapis\.com[^"]+)">/;
const m = html.match(linkRe);
let fontCss = '';
if (m) {
  const css = await (await fetch(m[1].replace(/&amp;/g, '&'), { headers: { 'User-Agent': UA } })).text();
  const blocks = css.split('/* ').filter(b => b.startsWith('latin */'));
  for (const b of blocks) {
    const url = b.match(/url\((https:[^)]+\.woff2)\)/)[1];
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    fontCss += b.replace('latin */', '').replace(url, 'data:font/woff2;base64,' + buf.toString('base64'));
  }
  html = html.replace(linkRe, '').replace(/<link rel="preconnect"[^>]*>/, '');
}
html = html.replace(/<meta name="claude:viewport-fit-sides"[^>]*>\n?/, '');

const doc = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>${fontCss}</style>
</head><body>
${html}
</body></html>`;

writeFileSync(path.join(root, 'src/gameHtml.js'),
  '// Generated by scripts/build-game.mjs from game/viral-load.html. Do not edit by hand.\nexport default ' + JSON.stringify(doc) + ';\n');
console.log(`src/gameHtml.js written (${(doc.length / 1024).toFixed(0)} KB, fonts ${(fontCss.length / 1024).toFixed(0)} KB)`);
